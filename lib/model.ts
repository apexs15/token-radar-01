// The token radar's model (RADAR-2): one snapshot of the protocol universe in, one ranked board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a ceiling) and every other
// pre-token protocol that meets the watchlist's own definition, with no TVL floor at all: the early rows
// the radar exists to find. A protocol is pre-token when its record carries no token (no market cap, no
// CoinGecko id, no symbol); the snapshot's live-token protocols are kept apart and shown as the market's
// own values, never mixed into the ranked board. A wrapped, staked or bridged product of a token that
// already trades is not a launch of its own, so the board keeps the watchlist's own exclusions: no
// Bridge, Canonical Bridge, Liquid Staking, Liquid Restaking, Restaked BTC or CEX category, no versioned
// name, no whole word wrapped, staked or staking in the name, and no name that begins with an exchange.
//
// Implied value follows only from the snapshot's own figures, never from a hand-written list of names:
//
//   base       = tvl_usd x BASE_MULTIPLE                         (0.25: a launch is worth a quarter of TVL)
//   growthPct  = clamp(change_7d, -75, 300) per cent           (a wider window than the starter's: a
//                                                                protocol up 300% in a week is not the
//                                                                same as one up 120%, and the 4,448% week
//                                                                in this snapshot still cannot swamp the board)
//   growthMult = 1 + (growthPct / 100) x GROWTH_WEIGHT
//   maturity   = 0.5 + min(age_days, 1460) / 1460 x 0.5         (age_days unknown: 365; a protocol that
//                                                                has run four years with no token has
//                                                                waited the longest for a launch)
//   sizeMult   = 1 + 0.3 x clamp(log10(floor_usd / tvl_usd), 0, 1)
//                                                              (an early-stage premium, only below the
//                                                              floor: a $5M protocol's token can be worth
//                                                              more per dollar of TVL than a $2B one's)
//   implied    = max(1, round(base x growthMult x maturity x sizeMult))
//
// The constants are the radar's own, stated in the dashboard. No protocol name is ever special-cased:
// the same function scores every row.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

